import fs from "node:fs";
import path from "node:path";
import { buildDataset, toCsv, type Row } from "./bi-dataset";

// npm run bi:export — writes the demo dataset to analytics/data/ and the matching Power Query script
// to analytics/powerbi/queries.pq (column types are taken from the data, so the two never drift apart).
const root = path.join(process.cwd(), "analytics");
const out = path.join(root, "data");
fs.mkdirSync(out, { recursive: true });
const { tables, expected } = buildDataset();
for (const [name, rows] of Object.entries(tables)) fs.writeFileSync(path.join(out, `${name}.csv`), toCsv(rows));
fs.writeFileSync(path.join(out, "expected.json"), JSON.stringify(expected, null, 2) + "\n");

function columnType(rows: Row[], column: string) {
  const values = rows.map((row) => row[column]).filter((value) => value != null);
  if (values.length && values.every((value) => typeof value === "string" && /^\d{4}-\d{2}-\d{2}$/.test(value))) return "type date";
  if (values.length && values.every((value) => typeof value === "number")) return values.every((value) => Number.isInteger(value)) && !/_aud$|_pct$|price|close|fx|share|quantity/.test(column) ? "Int64.Type" : "type number";
  return "type text";
}
const queries = Object.entries(tables).map(([name, rows]) => {
  const types = Object.keys(rows[0]).map((column) => `{"${column}", ${columnType(rows, column)}}`).join(", ");
  return `// ===== Query: ${name}\nLoadCsv("${name}", {${types}})`;
});
fs.writeFileSync(path.join(root, "powerbi", "queries.pq"), `// Generated by npm run bi:export. Do not edit by hand.
// Each "===== Query:" block is one query in Power BI (Home → Transform data → New source → Blank query →
// Advanced editor, paste the block, then rename the query to the name after "Query:").
// Create the two helper queries first, in this order.

// ===== Parameter: DataFolder
// Home → Manage parameters → New: name DataFolder, type Text, value = full path of analytics\\data, e.g.
// C:\\Users\\you\\stock-tool\\analytics\\data

// ===== Query: LoadCsv
// CSVs are UTF-8 with "." decimals and ISO dates, so types are applied with the en-US culture
// whatever the regional settings of the PC opening the report.
(name as text, types as list) as table =>
let
    Source = Csv.Document(File.Contents(DataFolder & "\\" & name & ".csv"), [Delimiter = ",", Encoding = 65001, QuoteStyle = QuoteStyle.Csv]),
    Promoted = Table.PromoteHeaders(Source, [PromoteAllScalars = true]),
    Typed = Table.TransformColumnTypes(Promoted, types, "en-US")
in
    Typed

${queries.join("\n\n")}
`);
